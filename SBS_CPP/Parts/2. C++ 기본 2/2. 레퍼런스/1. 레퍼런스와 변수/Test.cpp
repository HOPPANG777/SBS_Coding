/*
	레퍼런스..

		-	이름이 존재하는 메모리 공간에
							( 변수 )
			하나의 이름을 더 부여하는 행위..

			ㄴ	변수에 [ 별명 ]을 붙여주는 행위..



		-	키워드 [ & ] 사용..

			-	두가지 용법..

				예)
					int nVal = 10;
					int *pVal = &nVal;	//	1)	주소값 얻기..

					int &rVal = nVal;	//	2)	레퍼런스 선언..

			
*/
//=====================================================
#include<iostream>
using namespace std;
//=====================================================
int Func1()
{
	int nVal = 20;
	int &ref = nVal;

	return nVal;
}
int Func2()
{
	int nVal = 20;
	int &ref = nVal;

	return ref;	//	ref는 int형 레퍼런스인데도
				//	반환이 가능..
}
int main()
{
	int nVal = 10;

	int &ref = nVal;

	//	cout << &nVal << " : " << &ref << endl << endl;

	nVal++;
	cout << "nVal : " << nVal <<endl;
	cout << "ref : " << ref << endl;

	

	ref++;
	cout << "nVal : " << nVal << endl;
	cout << "ref : " << ref << endl;

	cout << "Func1() : " << Func1() << endl;
	cout << "Func2() : " << Func2() << endl;

	return 0;
}
/*
	
	고찰..

		-	레퍼런스를 통하여 처리하는 연산..

			==	해당 참조 변수를 가지고 처리하는 연산..

			ㄴ	레퍼런스와 변수는 생성 과정의
				차이만 있을뿐 생성 되고나면
				거의 동일..

			ㄴ	상황에 따라 아주
				미묘한 차이가 존재..

				ㄴ	[ 클래스의 상속과 다형성 ] 참고..
*/
