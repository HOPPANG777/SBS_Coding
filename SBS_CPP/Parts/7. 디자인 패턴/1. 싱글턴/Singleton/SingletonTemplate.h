#pragma once
#include<iostream>
//======================================================
/*
	---------------
	1.	싱글톤 패턴
	---------------

		-	필요성
			-	전체 시스템에 걸쳐
				단 한개만 필요한
				시스템 자원..


		-	책임
			-	전체 시스템에서
				해당 객체가
				단 하나뿐이어야 함..
			-	해당 클래스로
				여러곳에서
				객체를 만들 수
				없어야 함..
			-	어디서든
				접근 가능..


		-	싱글톤 생성 단계

			1)	객체를
				여러곳에서
				만들수 없도록 한다..
				-	생성자를 private로 선언..
							( 또는 protected )
					-	외부에서
						객체 생성을
						하지 못하도록 함..
					-	생성자를 호출 하지 못하면
						객체가 생성되지 못함..


			2)	생성자 대신
				객체를 생성할
				객체생성 함수를
				제공..
				-	클래스 외부에서
					접근이 가능하도록
					public으로 선언..
				-	외부에서
					클래스 객체를
					생성할 수 없으므로
					static 함수로 선언..
				-	static 멤버 함수에서
					객체를 생성할 수 있도록
					해당 클래스 타입의
					멤버변수도
					static으로 선언..


			3)	객체생성 함수에서
				예외 처리..
				-	객체가 생성되었는지
					확인 후
					생성되었다면
					기존 생성된 메모리를
					활용함..
					-	포인터로 동적 생성함..
					-	객체생성 함수를
						처음 호출할 때
						객체 생성..
						-	그후 생성된 메모리를
							참조하도록 함..


			4)	생성된 메모리는
				프로그램 종료시점에
				파괴..
				-	static으로 선언..
					-	전역으로 관리됨..
				-	해당 객체를 파괴하는
					함수를 만들어서
					프로그램 종료 시점에
					호출함..

*/
//=================================================
template<typename T>
class CSingletonTemplate
{	
	//---------------------------
	//	4)	생성된 메모리는
	//		프로그램 종료시점에
	//		파괴..
	//		-	데이터를
	//			전역으로
	//			접근 가능하도록
	//			해야 함..
	static T* _pInstance;
	//---------------------------
protected:
	//	1)	객체를
	//		여러곳에서
	//		만들수 없도록 한다..
	CSingletonTemplate() {};
	virtual ~CSingletonTemplate() {};
	//---------------------------
public:
	//	2)	생성자 대신
	//		객체를 생성할
	//		객체생성 함수..
	static T* GetInst()
	{
		//	3)	객체생성 함수에서
		//		예외 처리한다..
		if (_pInstance == NULL)
			_pInstance = new T();

		return _pInstance;
	
	}//	static T* GetInst()
	//---------------------------
	//	4)	생성된 메모리는
	//		프로그램 종료시점에
	//		파괴..
	static void Destroy()
	{
		if (_pInstance != NULL)
		{
			delete _pInstance;
			_pInstance = NULL;
		}
	
	}//	static void Destroy()
	//---------------------------

};// class CSingletonTemplate
//======================================================
template <typename T> T* CSingletonTemplate<T>::_pInstance = NULL;
//======================================================