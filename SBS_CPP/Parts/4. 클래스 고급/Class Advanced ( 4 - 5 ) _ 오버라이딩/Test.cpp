//*
class CParent
{
public :
	//~CParent() { cout << "~CParent" << endl; }
	virtual ~CParent() { cout << "~CParent" << endl; }
};

class CChild : public CParent
{
	int* _pTmp;
public :
	CChild() { _pTmp = new int; }

	~CChild() { 
		delete _pTmp;
		cout << "~CChild" << endl;
	}
};

int main()
{
	CParent* pParent = new CChild();
	CChild* pChild = new CChild();

	delete pParent;
	cout << endl;
	delete pChild;

	return 0;
}
//*/
//=================================================
/*
	-	분석..
	
		-	pParent는 CChild 타입의 객체를
			가리키고 있지만
			CParent 타입의 포인터로
			가리키고 있으므로
			CChild 객체를
			CParent객체로 인식..

	해결

		-	~CParent()를 virtual로 선언.

		-	과정..

			1)	CParent 소멸자 호출 시도..

			2)	소멸자가 virtual 이므로
				CChild 소멸자를 호출..
				-	비록 이름은 다르지만( ~CParent(), ~CChild() )
					둘다 소멸자이므로
					virtual 함수를
					오버라이딩 했을때의 현상이
					그대로 적용..

			3)	CChild의 소멸자는
				CParent를 상속받으므로
				다시 CParent의 소멸자 호출..
*/
