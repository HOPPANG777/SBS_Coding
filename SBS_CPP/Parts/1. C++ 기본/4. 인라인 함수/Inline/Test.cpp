/*=======================================================================
	
    ----------------
	1.	인라인 함수..    
	----------------

        -   일반 함수 사용으로 인한
            장점과 단점..

            -------------------
            -   함수 호출 과정..
            -------------------

                1)  함수의 인자를 스택에 저장..

                2)  함수가 리턴될 때 돌아올 주소를
                    스택이나 레지스터에 저장..
                
                3)  함수의 시작 주소로 점프..

                4)  함수의 코드 실행..

                5)  함수에서 만들어진 지역변수와
                    스택에 저장된 매개변수를 해제하고
                    리턴값을 레지스터에 저장..

                6)  함수를 호출할 때
                    저장해둔 주소로 복귀..

                    ㄴ   다음에 수행할 문장의 위치..


            ----------
            -   장점..
            ----------

                -   재사용이 쉬움..

                -   코드의 수정이 용이..

                -   함수 이름을 통한
                    가독성 증대..

                -   타입 검사..( 매크로는 하지않음.. )

                    ㄴ  매개변수와 인자값이
                        일치하는지 검사..

                -   디버그 용이..
            

            ----------
            -   단점..
            ----------

                -   함수 호출시 발생하는 연산량이
                    발생하여 처리 속도 저하..

                -   크거나 복잡한 업무를 수행하는
                    함수의 경우 큰 차이는 없으나
                    일반적으로 사용하는 작은 함수의 경우
                    함수 호출에 필요한 시간이
                    실제 함수 코드를 실행하는데 걸리는
                    시간보다 늘어날 수 있음..


        --------------------
		-   [ 매크로 함수 ]의
            정의와 장점..
        --------------------
            
            -   [ 매크로 ]

                -   자주 사용하는 여러 개의 명령어를 묶어서
                    하나의 키 입력 동작으로 만든 것..

                    [ 참고 : https://namu.wiki/w/%EB%A7%A4%ED%81%AC%EB%A1%9C ]


            -   [ 매크로 함수 ]

                -   함수처럼 인자를 설정할 수 있는 매크로..

                    [ 참고 : https://coding-factory.tistory.com/695 ]

			예)	
			
				#define SQUARE(x)	((x) * (x))
				int main()
				{
					cout << SQUARE(5) << endl;
					return 0;
				}

				    위의 코드는 전처리과정으로 통해

				int main()
				{
					cout << ((5) * (5)) << endl;
					return 0;
				}
				
				    로 변경됨..


			-	전처리기에 의해 함수 호출 문장이
                함수의 몸체 부분으로 완전히 대치되버림..

                --------------------
				-	함수의 인라인화..
                --------------------

                    ----------
					-	장점..
                    ----------

						-	함수 호출과정이 사라지므로
                            성능상의 이점 발생..

							ㄴ	함수호출은 스택 메모리 공간의
                                할당을 요구하며 그에 대한
                                시간이 소요됨..

                    ----------
					-	단점..
                    ----------

						-	함수의 구현이 까다롭고
                            디버깅이 어려움..

						-	구현하고자하는 함수의 크기가 크다면
                            프로그램의 크기도 커짐..

							ㄴ	구현 내용의 소스가 그대로
                                대치되기 때문..

        -----------------
		-   inline 함수..
        -----------------

            -   매크로 함수와 일반 함수의
                장점을 결합한 방식을 제공..

                ㄴ   코드 복사..
                ㄴ   디버깅 가능..
                ㄴ   타입 검사..
                ㄴ   처리 속도 증가..


            ----------
            -   주의..
            ----------

                -   작고 간단한 함수만 사용 권장..

                    ㄴ  코드의 복사는 파일 크기를
                        증가시킴..


                -   재귀 함수, 가상 함수, 함수 포인터 등은
                    인라인 함수로 선언하더라도 적용되지 않음..

                -   인라인 함수의 정의는 헤더 파일에
                    포함되어야 함..

                    ㄴ  복사에 필요한 코드가 있어야 함..

                -   컴파일러에 따라 inline 선언이
                    성능 향상에 해가 된다고 판단될 경우,
                    그냥 무시하기도 함...

                -   매크로 함수는 전처리기에서 처리되지만
                    인라인 함수는 컴파일러에 의한
                    코드 대치 방식으로 호출될 코드를 삽입..

=======================================================================*/
#include<iostream>

using namespace std;

inline int IL_SQUARE(int x) { return x * x; }
#define MAC_SQUARE(x) x*x
int main()
{
    //  일반 함수를 호출할 때 처럼 
    //  인자의 값을 먼저 계산한 다음
    //  함수 호출이 진행..
	cout << IL_SQUARE(5+5) << endl;
    cout << MAC_SQUARE(5 + 5) << endl;
    //  ->  x*x -> x => 5 + 5
    //  ->  5 + 5 * 5 + 5
    //  ->  5 + 25 + 5

	return 0;
}
