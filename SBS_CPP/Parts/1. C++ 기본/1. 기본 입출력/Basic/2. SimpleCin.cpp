#include <iostream>

/*
	1)	cin..

		-	키보드로부터 데이터 입력..

		-	cin >> 입력 변수;

		-	>> 을 이용하여 연속적인
			데이터의 입력 가능..

			ㄴ	데이터간의 경계는 공백으로 구분..

				ㄴ	탭, 스페이스바, 엔터키 입력..

			ㄴ	cin >> 입력 변수 1 >> 입력 변수 2 >> 입력 변수 3.....
*/

int main()
{
	int val1, val2;

	//*	1-1)
	std::cout << "첫번째 숫자 입력 : ";
	std::cin >> val1;
	std::cout << "두번째 숫자 입력 : ";
	std::cin >> val2;
	//*/

	/*	1-2)
	std::cout << "두개의 숫자 입력 : ";
	std::cin >> val1 >> val2;
	//*/

	int result = val1 + val2;
	std::cout << "덧셈 결과 :" << result << std::endl;

	return 0;
}
