#include <iostream>

int main()
{
	/*	2-1)	std::
	
				-	네임 스페이스 std, 이름 공간..

				-	범위 지정 연산자 ::
	*/
	

	/*	2-2)	cout..
	* 
				-	출력함수..

				-	cout << 출력 대상;

				-	출력 대상을
					연속으로 표시가능..

					ㄴ	출력할 대상이 둘 이상이라면
						<< 연산자를 이용하여
						연속으로 출력 가능..

					-	cout << 출력 대상 1 << 출력 대상 2 << 출력 대상 3 ....

				-	endl

					ㄴ	개행문자..

	*/
	std::cout << "Hello World !! " << std::endl;
	std::cout << "Hello " <<"World !!"<< std::endl;
	std::cout << 11 << 't' << "hStreet" << std::endl;

	return 0;
}
