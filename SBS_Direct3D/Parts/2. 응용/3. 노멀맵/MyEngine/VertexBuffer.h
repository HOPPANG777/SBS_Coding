/*	3. 노멀맵


	----------
	-	개요..
	----------
		-	면의 세밀한 요철( 울퉁 불퉁한 부분 )을
			표시하는 기법..
		-	입체감에 대한 정보값을
			2D 이미지로 설정하여
			하이 폴리곤처럼 연출하는 기법..


	----------
	-	방식..
	----------
		-	1)	법선 이미지( Normal Map )를
				폴리곤 정점에 매핑.
				-	참고 : [ texture / env2.bmp ], [ texture / normal.bmp ]
			2)	텍스쳐가 매핑된 면
				내부의 픽셀들의 값( 법선 벡터 )과
				광원의 방향 벡터를 내적 연산..
			3)	2) 결과를 해당 픽셀의 색으로 지정.
				-	법선 맵의 픽셀 값.
					=	색상을 나타내는 RGB가 아닌
						해당 픽셀에서의 방향을 나타내는
						법선 벡터로 사용..


	---------------------------------
	-	노멀맵의 색이 푸른 색인 이유..
	---------------------------------
	
		-	각 픽셀에 대한 노멀벡터의
			x축은 r채널,
			y축은 g채널,
			z축은 b채널로 표현.
			-	z축 값( b채널 )으로
				높이를 설정..

			각 픽셀의 노멀벡터를 정규화.
				xyz :	-1 ~ 0.0 ~ +1
						
					( value * 0.5 + 0.5 )

				rgb :   0 ~	0.5 ~ +1


		-	노멀벡터의 각축은
			방향에 따라
			음수, 0, 양수값을 가질수 있지만
			
			높이값은
			기준이 되는 지면에 대한
			상대적인 값이므로
			0보다 작을수 없음..

		-	z축 즉 노멀 값은
			시작점에서 커지는 값(높이)으로
			0 보다 작을수가 없음..
			-	z축 : 0
				---> b : 0.5
			-	모든 픽셀의 최소값은
				rgb( 0, 0, 0.5 )이므로
				푸른 빛..

*/
