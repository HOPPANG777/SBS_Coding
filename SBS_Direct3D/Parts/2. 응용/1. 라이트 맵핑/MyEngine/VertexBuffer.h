/*	
	라이트 맵핑 - 0)

		-------------------------------------------------
		1)	텍스쳐 좌표계
		-------------------------------------------------

			-----------
			-	정의
				-	2차원인 텍스처 이미지를
					3차원 공간의 폴리곤에
					입히기 위해 변환할때
					기준이 되는 좌표계..

			-----------
			-	특징
				-	x,y좌표와 구분되는
					u,v 좌표로 구성..
					-	uv좌표계라 불림.

				-	각 좌표는
					0.0 ~ 1.0 사이의
					실수값으로 구성..
					-	비율..

				-	텍셀좌표계( 텍스처 + 픽셀 )
					-	uv좌표값에 의해
						실제로 결정되는
						텍스처 이미지의 픽셀값..
					-	동일한 uv 좌표값이라도
						텍스처의 크기에 따라
						다른 텍셀값을 가질수 있음..
						

		-------------------------------------------------
		2)	텍스처 필터링
		-------------------------------------------------
			-	정의
				-	uv 좌표값으로부터
					텍스처의 텍셀값을
					읽어올때 발생하는
					*계단현상을 막기위해
					사용하는 기법..

					* 계단현상( 엘리어싱, aliasing )
						-	화면은 픽셀로 이루어져 있어서
							그래픽을 표현할때
							각진 선의 계단 모양을 나타냄..
							-	픽셀은 작은 사각형 모양임..

			-	주요 필터링 방식.

				====================================================================
				종류			|	이름			|	특징
				====================================================================
				POINT			|	최근점 / 근접점	|	해당 텍셀의 색에
								|	샘플링			|	가장 근접한
								|					|	정수값으로 변환..
								|					|-------------------------------
								|					|	기본 필터링 방식..
								|					|-------------------------------
								|					|	품질이 가장 낮지만
								|					|	계산이 가장 빠름..
				--------------------------------------------------------------------
				LINEAR			|	선형 필터링		|	선택된 텍셀의
								|					|	상하좌우 픽셀들의 평균값..
								|					|-------------------------------
								|					|	가장 선호하는 방식.
				--------------------------------------------------------------------
				ANISOTROPIC		|	이방성 필터링	|	* 밉맵으로부터
								|					|	여러 픽셀을 취해서 얻는 값..
								|					|-------------------------------
								|					|	품질이 가장 높지만
								|					|	계산속도가 가장 느림..
				====================================================================


		-------------------------------------------------
		3)	멀티 텍스처( Multi Texture )
		-------------------------------------------------
			-	정의.
				-	다중 텍스처..
				-	하나의 폴리곤에
					여러 장의 텍스처가
					중첩되어 출력되는 것..
				-	텍스쳐 스테이지..
					-	텍스처 관련 연산 처리를 위해
						텍스처들이 임시로 보관되는 영역..
					-	D3D9의 경우
						총 8개의 텍스처 스테이지 지원..
						-	그래픽카드의 성능상의 제한으로
							보통 2 ~ 4장 정도 사용..
						-	[ Directx Caps Viewer ]
							> [ Direct3dD9 Devices ]
							> [ 그래픽 카드 모델명 ]
							> [ D3D Device Types ]
							> [ HAL ]
							> [ Caps 카테고리 ]
							> [ MaxTextureBlendStages ]

			-	작동원리 [ 참고 : https://m.blog.naver.com/sipack7297/220424403817 ]
				-	두개의 텍스처를
					텍스처 스테이지에 전달
					-> 합성
					-> 다음 단계의 스테이지로 전달
					-> 다른 텍스처와 합성
					-> 다음 단계의 스테이지로 전달
					-> 다른 텍스처와 합성
					.... 최대 8번 반복
					-> 합성된 결과를
					   폴리곤에 적용.

	-------------------------------------------------
	라이트 맵핑 - 1)
		
		-	원리
			-	실시간 광원 연산에는
				매우 많은 연산량이 필요함..
			-	연산량을 줄이기 위해
				멀티 텍스처 기법을 이용하여
				광원 모양의 텍스처( 라이트맵 )를
				대상 텍스처에 합성..

		-	방식
			1)	그래픽 디자이너가 라이트맵을 생성하고
				프로그래머가 합성..

			2)	라이트 맵핑을 입힐 폴리곤을
				평면의 방정식으로 분해한뒤
				광원의 속성값에 따라서
				( 위치, 방향, 밝기, 색, 감쇠도 등 )
				라이트 맵을 만들어 적용.
				-	유니티, 언리얼등
					게임엔진 자체에서 지원..
	-------------------------------------------------

*/
struct SVtxDTxtr
{
	float x, y, z;
	DWORD color;
	float u, v;
};

