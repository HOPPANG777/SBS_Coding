/*
	4. 픽킹

	-	스크린 좌표를 이용해
		선택한 물체를 판별하는 기술..

	-	픽킹 광선을 계산한 후
		월드안의 각 물체를 대상으로
		광선과 교차하는지 테스트..

	-	활용..
		-	적을 클릭하여 무기 발사,
			아이템을 클릭하여 획득 등.

	-	방식.
			1)	스크린 좌표상의 선택지점( 마우스 좌표 )을
				월드 좌표로 변환.

				-	마우스 좌표( 스크린 좌표 ) --> 월드 좌표..

				-	렌더링 파이프 라인

					로컬 좌표
						-- 월드 변환 --> 월드 좌표
						-- 카메라 변환 --> 카메라 좌표
						-- 투영 변환 --> 투영 좌표
						-- 뷰포트 변환( DX 내부 변환 ) --> 뷰포트 좌표( 스크린 좌표 )
					
					-	위 방식을 역으로 적용.

			2)	픽킹 광선 계산..
				-	카메라의 위치로부터
					변환된 좌표로 가상의 선을 만듬..

			3)	광선 변환
				-	광선과 물체가
					교차하는지 확인하기 위해선
					서로 동일한 좌표계 시스템으로
					처리되어야 함..

			4)	3)에서 만든 광선과
				교차하는 물체가 있는지 체크..
				-	계산한 픽킹 광선이
					다수의 물체와 교차될 수도 있음..
					-	카메라와 가까운 물체를
						선택한 것으로 처리..
						( 가까운 물체가
						  먼 물체를 가리기 때문.. )
*/
