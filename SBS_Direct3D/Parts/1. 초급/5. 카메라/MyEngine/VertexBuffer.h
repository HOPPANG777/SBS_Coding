// 정점 구조체
struct SVtxNor
{
	//-------------------------------
	D3DXVECTOR3 _pos;	//	정점 위치, 위치 벡터..
	D3DXVECTOR3 _nor;	//	라이팅이 적용되기 위해서
						//	법선벡터는 필수, 방향 벡터..
	//-------------------------------
	SVtxNor() { _pos = _nor = D3DXVECTOR3(0, 0, 0); }
	//-------------------------------	
	SVtxNor(D3DXVECTOR3 pos, D3DXVECTOR3 nor)
	{
		_pos = pos;
		_nor = nor;
	}
	//-------------------------------
};
#define D3DFVF_CUSTOM ( D3DFVF_XYZ | D3DFVF_NORMAL )
