// 정점 구조체
struct SVtxTxtr
{
	//-------------------------------
	D3DXVECTOR3 _pos;	//	정점 위치
	float _u, _v;		//	텍스쳐 좌표.
	//-------------------------------
	SVtxTxtr() { ZeroMemory(this, sizeof(this)); }
	//-------------------------------	
	SVtxTxtr(D3DXVECTOR3 pos, float u, float v)
	{
		_pos = pos;
		_u = u;
		_v = v;
	}
	//-------------------------------
};
#define D3DFVF_CUSTOM ( D3DFVF_XYZ | D3DFVF_TEX1 )
