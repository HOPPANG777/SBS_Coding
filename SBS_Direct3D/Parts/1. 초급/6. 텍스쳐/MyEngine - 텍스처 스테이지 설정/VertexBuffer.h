// 정점 구조체
struct SVtxDTxtr
{
	//-------------------------------
	D3DXVECTOR3 _pos;		//	정점 위치
	D3DCOLOR    _color;		//	색깔
	float _u, _v;			//	텍스쳐 좌표.
	//-------------------------------
	SVtxDTxtr() { ZeroMemory(this, sizeof(this)); }
	//-------------------------------	
	SVtxDTxtr(D3DXVECTOR3 pos, D3DCOLOR color, float u, float v)
	{
		_pos = pos;
		_color = color;
		_u = u;
		_v = v;
	}
	//-------------------------------
};
#define D3DFVF_CUSTOM ( D3DFVF_XYZ | D3DFVF_DIFFUSE | D3DFVF_TEX1 )
