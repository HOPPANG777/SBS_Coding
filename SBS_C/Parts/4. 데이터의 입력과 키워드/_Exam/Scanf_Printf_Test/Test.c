/*
	Q)	다음과 같이 처리되는 프로그램을
		scanf, printf 를 이용하여 만듭니다.

		예)
			나이를 입력해주세요 : 20
			행운의 숫자를 입력해주세요 : 7

			당신은 20살이며 행운의 숫자는 7 입니다.
*/
//======================================================
#pragma warning( disable : 4996 )
//======================================================
#include <stdio.h>
//======================================================
int main(void)
{
	int age;
	int luckyNumber;

	printf("나이를 입력해주세요 : ");
	scanf("%d", &age);

	printf("행운의 숫자를 입력해주세요 : ");
	scanf("%d", &luckyNumber);

	printf("당신은 %d살이며 행운의 숫자는 %d 입니다.\n"
			, age, luckyNumber);

	return 0;
}
