/*
	------------------------
	1]	rand 함수..
	------------------------
		1)	원형.

			-	#include <stdlib.h>
				int rand(void);


		2)	특징

			- 0 ~ 32767 의 범위중 무작위 수를 추출
			- seed 값에 따라 발생하는 난수의 값이 결정 
*/

/*	1) 랜덤 예제 소스..
int main()
{
	printf("%d \n",rand());
	printf("%d \n",rand());
	printf("%d \n",rand());
	printf("%d \n",rand());
	return 0;
}
//*/


/*
	------------------------
	2]	랜덤 씨드 설정..
	------------------------

		-	위의 예제 소스는 rand()를 사용했는데 몇번을 호출해도 같은 값이 출력됨.
		-	rand()는 난수표( seed )라는 곳을 참고하여 난수값을 반환함.
		-	난수표를 설정해주지 않으면 기본 난수표로부터 값을 가져옴.
			-	rand()를 사용할때 마다 난수표를 설정해줘야 함.


	------------------------
	3]	srand 함수..
	------------------------
	
			1)	원형.

				-	#include <stdlib.h>
					void srand (unsigned int seed);


			2)	특징

				-	난수에 발생되는 seed 값을 설정.

*/

/*	2) 랜덤 예제 소스..
int main()
{
	srand(100);
	printf("%d \n", rand());
	printf("%d \n", rand());
	printf("%d \n", rand());
	printf("%d \n", rand());
	return 0;
}
//*/

