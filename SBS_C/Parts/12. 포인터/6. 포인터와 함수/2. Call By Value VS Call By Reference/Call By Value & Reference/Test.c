//	n1과 n2를 바꾸는 함수..
void Swap(int n1, int n2)
{
	int tmp = n1;
	n1 = n2;
	n2 = tmp;

	printf("n1 = %d,   n2 = %d\n", n1, n2);
}

int main(void)
{
	int n1 = 10;
	int n2 = 20;
	printf("n1 = %d,   n2 = %d\n", n1, n2);

	Swap(n1, n2);

	printf("n1 = %d,   n2 = %d\n", n1, n2);

	return 0;	
}
