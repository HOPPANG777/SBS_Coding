/*
	-------------------------------------
	6.	register 변수
	-------------------------------------
	
		특징..

			-	지역변수 앞에
				register 라는 키워드를
				붙혀서 선언..

				예) register int num = 1;

			-	cpu내에 존재하는
				레지스터라는 메모리 공간에
				저장될 확률이 높아짐..

				- 레지스터
					-	cpu내에 존재하는
						크기가 매우 작은 메모리..
					-	cpu내에 존재하므로
						이 메모리에 저장된 데이터를
						대상으로 하는 연산은
						매우 빠름..

			-	컴파일러는 이 선언을 바탕으로
				레지스터 활용여부를 결정..

			-	register 선언을 추가하더라도
				컴파일러가 적당하지 않다고 판단하면
				레지스터에 할당하지 않음..

				register 선언을
				추가하지 않았어도
				컴파일러가 레지스터에
				할당해야겠다고
				판단하면 그 변수는
				레지스터에 할당됨..
					
			-	전역변수의 경우
				프로그램의 시작부터
				종료시까지
				메모리에 할당되야하므로 
				레지스터 변수로
				처리하기엔 무리..

			->	컴퓨터 성능과
				컴파일러의 성능이
				향상됨에 따라
				레지스터의 필요성이
				낮아짐..
						
*/
