/*	
	방법 1)	#pragma 지시문..

	-	컴퓨터 또는 운영 체제별
		컴파일러 기능을 지정 하거나
		C 및 C++ 언어와의
		전반적인 호환성을 유지
		( warning, once... 등 )

	-	#pragma once
		-	컴파일러( 실제로는 전처리기 )에게
			#pragma once가 선언된 파일은
			한번만 읽어들이라고 지시..
		-	컴파일러가 해당 파일은
			한번만 읽으면 된다는 것을 알기 때문에
			파일 리스켄 필요없음..

	-	표준 방식은 아님.
		-	GCC와 VC 컴파일러에서는
			동작하나
			다른 컴파일러에선
			동작 안할수도 있음..
*/
//===============================================
#pragma once
//===============================================
/*
	방법 2)	헤더 가드 시작..
	-	#ifndef 매크로 처리기를 통해
		특정 매크로가 선언되어 있으면
		조건이 참이 아니므로
		#endif 까지의 코드가 무효화..
	-	#include "xxx.h"를 발견할 때마다
		xxx.h 파일을 스캔하여
		매크로가 이미 선언되었는지 체크..
*/
#ifndef ADD_H
#define ADD_H
//===============================================
//	헤더 파일 실제 구현 부..

int Plus(int x, int y);
int Minus(int x, int y);

//===============================================
//	헤더 가드 종료..
#endif	//	#ifndef ADD_H
//===============================================
